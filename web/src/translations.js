// Server error codes are snake_case; an unknown one gets the generic server
// message. Any other missing key is a missing label, not a server failure, so it
// shows its last segment (and warns during development) instead of "server error".
const errorCode = /^[a-z0-9]+(?:_[a-z0-9]+)*$/;
const warned = new Set();
export function translate(language, key) {
  const index = language === "ar" ? 0 : 1;
  const text = workflowCopy[key]?.[index] ?? translations[key]?.[index];
  if (text) return text;
  if (!key || errorCode.test(key)) return translations.server_error[index];
  if (import.meta.env?.DEV && !warned.has(key)) {
    warned.add(key);
    console.warn(`Missing translation: ${key}`);
  }
  const label = String(key).split(".").pop();
  return label === "undefined" || label === "null" ? "—" : label;
}
